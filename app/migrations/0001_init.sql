CREATE TABLE state (id INTEGER PRIMARY KEY CHECK (id = 1), json TEXT NOT NULL, updated_at TEXT NOT NULL);
CREATE TABLE constraints (id TEXT PRIMARY KEY, json TEXT NOT NULL);
CREATE TABLE club_events (id TEXT PRIMARY KEY, date TEXT NOT NULL, json TEXT NOT NULL);
CREATE TABLE action_log (id INTEGER PRIMARY KEY AUTOINCREMENT, at TEXT NOT NULL, json TEXT NOT NULL);
CREATE TABLE lift_log (id INTEGER PRIMARY KEY AUTOINCREMENT, date TEXT NOT NULL, lift TEXT NOT NULL, json TEXT NOT NULL);
CREATE TABLE activities (id TEXT PRIMARY KEY, date TEXT NOT NULL, source TEXT NOT NULL, json TEXT NOT NULL);
CREATE TABLE mobility_log (date TEXT PRIMARY KEY, status TEXT NOT NULL);
CREATE TABLE sent_reminders (kind TEXT NOT NULL, local_date TEXT NOT NULL, PRIMARY KEY (kind, local_date));
CREATE TABLE kv (key TEXT PRIMARY KEY, value TEXT NOT NULL);
